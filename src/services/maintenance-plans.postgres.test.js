import {afterAll,beforeAll,beforeEach,describe,it,expect,vi} from "vitest";
import pg from "pg";
import {loadEnvLocal} from "../../scripts/load-env.mjs";
vi.mock("@/lib/db",()=>({query:vi.fn(()=>{throw new Error("Global query forbidden");})}));
import {saveServicePlan,recordOdometerObservation,syncRoutinePlanFromLegacy,listServicePlans} from "./maintenance-plans.service";
import {recomputeVehicleSchedule} from "./maintenance-schedule.service";
let client;
describe.skipIf(process.env.MAINTENANCE_FIXTURE_DB_TEST!=="1")("private service plans and rollback-only SQL behavior",()=>{
 beforeAll(async()=>{loadEnvLocal();client=new pg.Client({connectionString:process.env.DATABASE_URL,ssl:{rejectUnauthorized:false},connectionTimeoutMillis:5000});await client.connect();});
 afterAll(async()=>{try{await client?.query("ROLLBACK");}finally{await client?.end();}});
 it("has private tables with RLS and zero anon/authenticated grants",async()=>{
  const rows=(await client.query(`SELECT c.relname,c.relrowsecurity,
  EXISTS(SELECT 1 FROM information_schema.role_table_grants g WHERE g.table_schema='public' AND g.table_name=c.relname AND grantee IN ('anon','authenticated','PUBLIC')) AS exposed
  FROM pg_class c WHERE c.oid IN (to_regclass('public.vehicle_service_plans'),to_regclass('public.vehicle_odometer_observations')) ORDER BY relname`)).rows;
  const staff = await listServicePlans({role:"fleet_manager"},null,client);
  expect(staff.length).toBeGreaterThanOrEqual(0);
  expect(await listServicePlans({role:"mechanic",employeeId:-1},null,client)).toEqual([]);
  expect(rows).toEqual([{relname:"vehicle_odometer_observations",relrowsecurity:true,exposed:false},{relname:"vehicle_service_plans",relrowsecurity:true,exposed:false}]);
 });
 describe("temporary fixtures",()=>{
 beforeAll(async()=>{
  await client.query("BEGIN; SET LOCAL search_path TO pg_temp,pg_catalog; SET LOCAL statement_timeout='8s'");
  await client.query(`CREATE TEMP TABLE vehicles(vehicle_id int PRIMARY KEY,mileage numeric,deleted_at timestamptz,service_interval_days int,service_interval_km int,last_service_date date,next_service_date date,next_service_mileage numeric,updated_at timestamptz);
  CREATE TEMP TABLE vehicle_service_plans(LIKE public.vehicle_service_plans INCLUDING CONSTRAINTS);
  ALTER TABLE vehicle_service_plans ALTER COLUMN plan_id ADD GENERATED BY DEFAULT AS IDENTITY;
  ALTER TABLE vehicle_service_plans ALTER COLUMN version SET DEFAULT 1;
  ALTER TABLE vehicle_service_plans ALTER COLUMN created_at SET DEFAULT NOW();
  ALTER TABLE vehicle_service_plans ALTER COLUMN updated_at SET DEFAULT NOW();
  ALTER TABLE vehicle_service_plans ADD PRIMARY KEY(plan_id),ADD UNIQUE(vehicle_id,service_code),ADD UNIQUE(plan_id,vehicle_id);
  CREATE TEMP TABLE vehiclemaintenance(maintenance_id int PRIMARY KEY,vehicle_id int,service_plan_id int,service_plan_version int,status text,deleted_at timestamptz,assigned_mechanic_id int,
   FOREIGN KEY(service_plan_id,vehicle_id) REFERENCES vehicle_service_plans(plan_id,vehicle_id));
  CREATE UNIQUE INDEX fixture_active_plan ON vehiclemaintenance(service_plan_id) WHERE service_plan_id IS NOT NULL AND deleted_at IS NULL AND status IN ('Scheduled','In Progress','Pending Inspection');
  CREATE TEMP TABLE vehicle_odometer_observations(LIKE public.vehicle_odometer_observations INCLUDING CONSTRAINTS);
  ALTER TABLE vehicle_odometer_observations ALTER COLUMN observation_id ADD GENERATED BY DEFAULT AS IDENTITY;
  ALTER TABLE vehicle_odometer_observations ALTER COLUMN recorded_at SET DEFAULT clock_timestamp();
  SAVEPOINT fixture`);
 });
 beforeEach(async()=>{await client.query("ROLLBACK TO SAVEPOINT fixture; INSERT INTO vehicles(vehicle_id,mileage) VALUES(7,1000),(8,500)");});
 const save=(code="routine",patch={interval_days:30,interval_km:5000},version=0)=>saveServicePlan(client,7,code,patch,version,null);
 it("rejects Routine fractional and overflowing kilometre intervals before legacy writes",async()=>{
  for(const interval_km of [5000.5,2147483648]) await expect(save("routine",{interval_km})).rejects.toMatchObject({status:400});
 });
 it("creates independent plans, preserves unknown history and mirrors Routine",async()=>{
  const {plan}=await save();await save("brakes",{next_service_date:"2026-12-01"});
  expect(plan.last_service_date).toBeNull();expect(plan.last_service_mileage).toBeNull();expect(plan.version).toBe(1);
  expect((await listServicePlans({role:"admin"},7,client)).map(p=>p.schedule_mode).sort()).toEqual(["interval","manual"]);
  expect((await client.query("SELECT service_interval_days FROM vehicles WHERE vehicle_id=7")).rows[0].service_interval_days).toBe(30);
 });
 it("increments versions, rejects stale updates and active cycle replacement",async()=>{
  const {plan}=await save();expect((await save("routine",{interval_days:60},1)).plan.version).toBe(2);
  await expect(save("routine",{interval_days:90},1)).rejects.toMatchObject({status:409});
  await client.query("INSERT INTO vehiclemaintenance VALUES(1,7,$1,2,'Scheduled',NULL,9)",[plan.plan_id]);
  await expect(save("routine",{interval_days:90},2)).rejects.toMatchObject({status:409});
 });
 it("rejects cross-vehicle linkage and duplicate active linked orders",async()=>{
  const {plan}=await save();await client.query("SAVEPOINT invalid");
  await expect(client.query("INSERT INTO vehiclemaintenance VALUES(1,8,$1,1,'Scheduled',NULL,9)",[plan.plan_id])).rejects.toMatchObject({code:"23503"});await client.query("ROLLBACK TO SAVEPOINT invalid");
  await client.query("INSERT INTO vehiclemaintenance VALUES(1,7,$1,1,'Scheduled',NULL,9)",[plan.plan_id]);
  await expect(client.query("INSERT INTO vehiclemaintenance VALUES(2,7,$1,1,'In Progress',NULL,9)",[plan.plan_id])).rejects.toMatchObject({code:"23505"});await client.query("ROLLBACK TO SAVEPOINT invalid");
 });
 it("keeps completion, service mileage, version and legacy columns together",async()=>{
  await save();await save("brakes",{interval_days:100});
  await recomputeVehicleSchedule(7,{status:"Completed",maintenance_type:"Routine",completed_date:"2026-10-01",mileage_at_service:1000},client);
  const rows=(await client.query("SELECT service_code,version,last_service_mileage,next_service_date::text,next_service_mileage FROM vehicle_service_plans ORDER BY service_code")).rows;
  expect(rows[0]).toMatchObject({service_code:"brakes",version:1,last_service_mileage:null,next_service_date:null});
  expect(rows[1]).toMatchObject({service_code:"routine",version:2,last_service_mileage:"1000.00",next_service_date:"2026-10-31",next_service_mileage:"6000.00"});
  expect((await client.query("SELECT next_service_mileage FROM vehicles WHERE vehicle_id=7")).rows[0].next_service_mileage).toBe("6000.00");
 });
 it("routes a legacy form edit to the authoritative plan",async()=>{
  await save();await syncRoutinePlanFromLegacy(client,7,{service_interval_days:60,next_service_date:"2026-12-01"},null);
  expect((await client.query("SELECT interval_days,version,next_service_date::text FROM vehicle_service_plans")).rows[0]).toEqual({interval_days:60,version:2,next_service_date:"2026-12-01"});
 });
 it("records manual dated evidence and preserves equal or increasing odometers",async()=>{
  const data={reading_km:1200,observed_at:"2026-10-01T12:00:00+08:00",reason:"Fleet check"};
  const row=await recordOdometerObservation(client,7,data,8);expect(row.recorded_at).toBeInstanceOf(Date);expect(row.reason).toBe("Fleet check");
  expect((await client.query("SELECT mileage FROM vehicles WHERE vehicle_id=7")).rows[0].mileage).toBe("1200");
  await expect(recordOdometerObservation(client,7,{...data,reading_km:1100},8)).rejects.toMatchObject({status:409});
 });
 it("rolls plan and odometer changes back together on a later failure",async()=>{
  await client.query("SAVEPOINT request");await save();await recordOdometerObservation(client,7,{reading_km:2000,observed_at:"2026-10-01T00:00:00Z",reason:"Check"},8);
  await client.query("ROLLBACK TO SAVEPOINT request");expect((await client.query("SELECT count(*)::int AS n FROM vehicle_service_plans")).rows[0].n).toBe(0);expect((await client.query("SELECT mileage FROM vehicles WHERE vehicle_id=7")).rows[0].mileage).toBe("1000");
 });
 });
});
