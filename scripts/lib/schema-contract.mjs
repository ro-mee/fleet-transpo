// The schema contract — what this application depends on, and how each table is
// allowed to be reached.
//
// This file exists because of `024`, which dropped a table that live code still
// queried. Nothing caught it until incident reporting broke in production, and
// `Capstone/03 - Database/Migrations/Migrations.md` recorded the gap plainly:
// *"There is still no check that the schema satisfies the code."* This is that
// check's offline half.
//
// It is deliberately hand-maintained and readable. It is a statement of intent,
// not a dump — a dump already exists (`schema.sql`, regenerated by `db:dump`)
// and a dump cannot tell you whether a table *should* be reachable. That is the
// part only a person can say, so it lives here in prose.
//
// TWO JOBS
// --------
// 1. **Dependency list.** Every table the application reads or writes. The
//    security suite fails if a migration in `supabase/migrations/` would drop,
//    rename or narrow one of them, and if any table in `src/**` is missing here.
// 2. **Access-classification registry.** Every table in `public` carries
//    `private` or `public` plus a reason. A table that appears in the database
//    and nowhere here fails the run.
//
// THE INVARIANT IS NOT "NO TABLE GRANTS SELECT TO anon"
// -----------------------------------------------------
// That rule would be wrong on Supabase. A grant and a row filter are separate
// mechanisms, and a table may legitimately hold a `SELECT` grant while RLS
// correctly limits which rows are visible. The meaningful question is not *"is
// there a grant"* but *"does this table's classification match how it actually
// behaves."* So the live check (`npm run db:contract`) asserts, per table:
//
//   private  →  RLS enabled, no anon-permissive policy, and the anon probe
//               does not return protected rows
//   public   →  allowlisted here WITH its intended anon-read policy stated and
//               verified. A `public` tag is a documented decision, never an
//               exemption from having one.
//
// WHY EVERY TABLE IS `private`
// ----------------------------
// Verified 2026-09-18, not assumed. The anon key ships in the browser bundle by
// design, and the browser client (`src/lib/supabase/client.js`) is real — but
// its only consumers are `useRealtime` / `useTrackingRealtime`
// (`src/hooks/use-realtime.js`), and **both hooks have zero callers**. No
// component reads a table with the anon key. Everything goes through `/api/**`,
// which authenticates per-route and reaches Postgres as the owner.
//
// So there is no intentionally-public table, and this file should not invent
// one to have a positive control. If a client-side read is ever added, the
// table it touches is the first `public` entry — and it must state the policy
// that makes that safe.
//
// Related: `Capstone/07 - Development/Bugs.md` SEC-DB-003 (three tables created
// after migration 100 never got RLS) and SEC-DB-004 (the schema dump cannot
// show RLS or grants at all).

